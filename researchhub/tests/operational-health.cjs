const fs=require("node:fs"),assert=require("node:assert/strict"),ts=require("typescript");
require.extensions[".ts"]=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,f);
const {operationalAlerts}=require("../lib/operations/health.ts");
const metrics={ai24h:10,aiFailed24h:3,aiReserved24h:1,ai7d:100,aiFailed7d:7,paymentsPending24h:2,paymentsStale:1,paymentsActivated7d:9,appErrorsOpen:2};
assert.deepEqual(operationalAlerts(metrics).map(a=>a.key),["ai-failure","ai-pending","payment-stale","app-errors"]);
assert.deepEqual(operationalAlerts({...metrics,ai24h:4,aiFailed24h:4,aiReserved24h:0,paymentsStale:0,appErrorsOpen:0}).map(a=>a.key),["none"],"Low volume must not yield a false critical alert");
assert.equal(operationalAlerts({...metrics,aiFailed24h:null})[0].key,"unavailable");
